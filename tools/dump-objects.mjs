// Generates crates/wd-core/src/objects_data.rs from the original object definitions
// (assets/scripts/game/allObjects.js plus the fix-ups level.js applies right after loading them).
import fs from "node:fs";
import vm from "node:vm";

const root = new URL("..", import.meta.url).pathname;
const ctx = vm.createContext({ console, Math, Object, Number, Array, Set, Map, JSON, Infinity, NaN });
ctx.window = ctx;
vm.runInContext(fs.readFileSync(root + "ref/assets/scripts/game/allObjects.js", "utf8"), ctx);
const lv = fs.readFileSync(root + "ref/assets/scripts/core/level.js", "utf8");
const a = lv.indexOf("const allObjects = window.allobjects();");
const b = lv.indexOf("const GD_SPEED_PIXELS_PER_SECOND");
vm.runInContext(lv.slice(a, b) + "\nthis.allObjects = allObjects;", ctx);
const lt = fs.readFileSync(root + "ref/assets/scripts/core/level-triggers.js", "utf8");
vm.runInContext("var triggerType = 'trigger'; window.LevelObject = { prototype: {} };\n" + lt.slice(0, lt.indexOf("  const rawValue")) + "})();", ctx);
ctx.allObjects[2065].type = "deco"; ctx.allObjects[2065].children = [];

const num = (v) => (typeof v === "number" && Number.isFinite(v) ? (Number.isInteger(v) && Math.abs(v) < 1e15 ? v.toFixed(1) : String(v)) : "f64::NAN");
const opt = (v) => (typeof v === "number" && Number.isFinite(v) ? `Some(${num(v)})` : "None");
const str = (v) => (typeof v === "string" ? `Some(${JSON.stringify(v)})` : "None");
const ids = Object.keys(ctx.allObjects).map(Number).filter(Number.isFinite).sort((x, y) => x - y);
let out = "// @generated by tools/dump-objects.mjs from assets/scripts/game/allObjects.js. Do not edit.\nuse crate::objects::ObjectDef;\n\npub static OBJECTS: &[(u32, ObjectDef)] = &[\n";
for (const id of ids) {
  const d = ctx.allObjects[id];
  if (!d || typeof d !== "object") continue;
  out += `    (${id}, ObjectDef { ty: ${str(d.type)}, grid_w: ${opt(d.gridW)}, grid_h: ${opt(d.gridH)}, sprite_w: ${opt(d.spriteW)}, sprite_h: ${opt(d.spriteH)}, hitbox_scale_x: ${opt(d.hitboxScaleX)}, hitbox_scale_y: ${opt(d.hitboxScaleY)}, hitbox_radius: ${opt(d.hitbox_radius)}, sub: ${str(d.sub)}, portal_particle_color: ${opt(d.portalParticleColor)} }),\n`;
}
out += "];\n";
fs.writeFileSync(root + "crates/wd-core/src/objects_data.rs", out);
console.log(ids.length, "objects written");
const types = {};
for (const id of ids) types[ctx.allObjects[id]?.type] = (types[ctx.allObjects[id]?.type] || 0) + 1;
console.log(types);

// Slope tables from level.js
const lvSlopes = lv.slice(lv.indexOf("const _SLOPE_DATA = {"), lv.indexOf("function _isDecorationSlopeId"));
vm.runInContext(lvSlopes.replace("const _SLOPE_DATA", "var _SLOPE_DATA").replace("const _SLOPE_DECO_RANGES", "var _SLOPE_DECO_RANGES").split("function _resolveSlopeDir")[0] + "\n" + lv.slice(lv.indexOf("const _SLOPE_DECO_RANGES"), lv.indexOf("function _isDecorationSlopeId")).replace("const _SLOPE_DECO_RANGES", "var _SLOPE_DECO_RANGES"), ctx);
const sd = ctx._SLOPE_DATA, ranges = ctx._SLOPE_DECO_RANGES;
let so = "// @generated by tools/dump-objects.mjs from the slope tables in assets/scripts/core/level.js. Do not edit.\n\n";
so += "/// (object id, grid width, grid height, angle in degrees, filled square)\npub static SLOPES: &[(u32, f64, f64, f64, bool)] = &[\n";
for (const id of Object.keys(sd).map(Number).sort((x, y) => x - y)) { const e = sd[id]; so += `    (${id}, ${num(e.gw)}, ${num(e.gh)}, ${num(e.angle)}, ${!!e.sq}),\n`; }
so += "];\n\npub static SLOPE_DECO_RANGES: &[(u32, u32)] = &[\n";
for (const [lo, hi] of ranges) so += `    (${lo}, ${hi}),\n`;
so += "];\n";
fs.writeFileSync(root + "crates/wd-core/src/slopes_data.rs", so);
console.log(Object.keys(sd).length, "slope entries,", ranges.length, "deco ranges");

// The full definitions (frames, children, glow, colours...) for the visual side
fs.mkdirSync(root + "crates/wd-core/data", { recursive: true });
const b2 = lv.indexOf("window._animatedSprites = [];");
vm.runInContext("var allObjects2 = (function(){ " + lv.slice(a, b2).replace(/^const allObjects = /m, "const allObjects = ") + "\n" + lt.slice(0, lt.indexOf("  const rawValue")).replace("(() => {", "") + "\n if (allObjects[2065]) { allObjects[2065].type = 'deco'; allObjects[2065].children = []; }\n return allObjects; })()", ctx);
fs.writeFileSync(root + "crates/wd-core/data/objects_full.json", JSON.stringify(ctx.allObjects2));
console.log("objects_full.json written");
